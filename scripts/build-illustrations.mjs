// Turns the unDraw SVGs dropped into illustrations-src/ into theme-aware inline SVG strings
// (src/components/illustrations/illustrations.generated.ts). unDraw's accent colour is
// rewritten to --action-primary and its greys/inks/white to V2 surface/text tokens, so every
// illustration follows light, midnight and dimmed. Run: node scripts/build-illustrations.mjs
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'illustrations-src';
const OUT = 'src/components/illustrations/illustrations.generated.ts';
const PRIMARY = '#4274d9'; // --primary-500 — the accent colour chosen on undraw.co

// Each slot is read from illustrations-src/<slot>.svg (an unDraw download, accent #4274D9).
// To use a different unDraw piece for a state, replace that file. Spare downloads live in
// illustrations-src/_unused/.
const SLOTS = [
  'not-found', 'no-access', 'error', 'success', 'empty-inbox',
  'empty-reports', 'no-results', 'team', 'onboarding', 'empty-forms',
  // second batch — icon fallback until the file exists
  'link-expired', 'invite', 'email-sent', 'form-closed', 'pipeline', 'calendar', 'build-form', 'notifications',
];

const hex = (h) => {
  h = h.replace('#', '').toLowerCase();
  if (h.length === 3) h = [...h].map((c) => c + c).join('');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
function token(color) {
  const c = color.toLowerCase();
  if (c === PRIMARY) return 'var(--action-primary)';
  const [r, g, b] = hex(c);
  const max = Math.max(r, g, b) / 255, min = Math.min(r, g, b) / 255;
  const l = (max + min) / 2;
  const sat = max === min ? 0 : (max - min) / (1 - Math.abs(2 * l - 1));
  if (sat > 0.25) return null; // skin tones, hair, accents of other hues stay as drawn
  if (l >= 0.98) return 'var(--surface-card)';
  if (l >= 0.93) return 'var(--bg-sunken)';
  if (l >= 0.78) return 'var(--border-default)';
  if (l >= 0.5) return 'var(--text-disabled)';
  if (l >= 0.2) return 'var(--text-secondary)';
  return 'var(--text-primary)';
}
function tokenise(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s(width|height)="[^"]*"/g, (m, k, off) => (off < 400 ? '' : m)) // root size only
    .replace(/#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g, (m) => token(m) ?? m)
    .replace(/<svg\b/, '<svg focusable="false" aria-hidden="true"')
    .replace(/\s+/g, ' ')
    .trim();
}

const out = {};
for (const slot of SLOTS) {
  const file = path.join(SRC, `${slot}.svg`);
  if (!fs.existsSync(file)) { console.log(`  - ${slot}: missing ${file} (icon fallback stays)`); continue; }
  out[slot] = tokenise(fs.readFileSync(file, 'utf8'));
  console.log(`  + ${slot}`);
}

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/build-illustrations.mjs from illustrations-src/ — do not hand-edit.\n` +
    `export const ILLUSTRATION_NAMES = ${JSON.stringify(SLOTS)} as const;\n` +
    `export type IllustrationName = (typeof ILLUSTRATION_NAMES)[number];\n` +
    `export const ILLUSTRATIONS: Partial<Record<IllustrationName, string>> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`Wrote ${OUT} (${Object.keys(out).length}/${SLOTS.length} slots filled)`);
