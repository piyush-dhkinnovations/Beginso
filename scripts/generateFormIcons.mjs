// Builds src/lib/formIconData.generated.ts: the form icon picker's icons, taken from the Streamline "Ultimate Color" free set
// (npm: @iconify-json/streamline-ultimate-color, CC BY 4.0 - Streamline, https://streamlinehq.com). Only the icons listed in
// scripts/formIconSet.json are copied, so the app ships a few dozen KB instead of the whole 998-icon set.
//
//   npm run generate:form-icons
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@iconify-json/streamline-ultimate-color/package.json'));
const set = JSON.parse(readFileSync(join(pkgDir, 'icons.json'), 'utf8'));
const list = JSON.parse(readFileSync(join(root, 'scripts', 'formIconSet.json'), 'utf8')).icons;

const SLUG = /^[a-z0-9-]{2,40}$/;
const HEX = /^#[0-9A-Fa-f]{6}$/;
const seen = new Set();
const entries = list.map((i) => {
  if (!SLUG.test(i.name)) throw new Error(`"${i.name}" is not a valid icon slug (a-z, 0-9, hyphen, 2-40 chars)`);
  if (seen.has(i.name)) throw new Error(`"${i.name}" is listed twice`);
  seen.add(i.name);
  if (!HEX.test(i.color)) throw new Error(`"${i.name}" has no valid #RRGGBB colour`);
  const icon = set.icons[i.name];
  if (!icon) throw new Error(`"${i.name}" is not in the Streamline Ultimate Color set`);
  // The body is the SVG's inner markup on a 24x24 canvas. It comes from the package, never from a user.
  return { ...i, body: icon.body };
});

const header = `// GENERATED by scripts/generateFormIcons.mjs from scripts/formIconSet.json - do not edit by hand.
// Icons: Streamline "Ultimate Color" free set, CC BY 4.0, https://streamlinehq.com (credit required, shown in the icon picker).
`;
const body = `export interface FormIconRecord {
  name: string;
  label: string;
  keywords: string;
  /** A representative hue of the icon. */
  color: string;
  featured: boolean;
  /** SVG inner markup on a 24x24 canvas. */
  body: string;
}

export const FORM_ICON_DATA: FormIconRecord[] = ${JSON.stringify(
  entries.map((e) => ({ name: e.name, label: e.label, keywords: e.keywords, color: e.color, featured: !!e.featured, body: e.body })),
  null,
  2
)};
`;
writeFileSync(join(root, 'src', 'lib', 'formIconData.generated.ts'), header + body);
console.log(`Wrote ${entries.length} icons (${entries.filter((e) => e.featured).length} featured).`);
